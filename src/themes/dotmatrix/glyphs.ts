/** Characters every Dot Matrix surface relies on (checked by tests). */
export const REQUIRED_GLYPHS = "0123456789:%°/.-ABCDEFGHIJKLMNOPQRSTUVWXYZ";

export interface Dot {
  x: number;
  y: number;
}

export interface DotLayout {
  dots: Dot[];
  /** Grid columns used, including 1-column gaps between glyphs. */
  cols: number;
  rows: 7;
}

/**
 * Lays out `text` as dot coordinates on a cell grid. Lower-case letters are drawn as capitals;
 * unknown characters become a space. Deterministic: the same text always gives the same dots.
 */
export function layoutDots(text: string): DotLayout {
  const dots: Dot[] = [];
  let col = 0;
  const chars = [...text.toUpperCase()];
  chars.forEach((ch, i) => {
    const g = DOT_GLYPHS[ch] ?? DOT_GLYPHS[" "];
    const w = g[0].length;
    for (let y = 0; y < 7; y++) {
      for (let x = 0; x < w; x++) if (g[y][x] === "#") dots.push({ x: col + x, y });
    }
    col += w + (i < chars.length - 1 ? 1 : 0);
  });
  return { dots, cols: col, rows: 7 };
}

/* ---------- Weather pictograms (7×7) ---------- */

export type WeatherKind = "sun" | "cloud" | "rain" | "snow" | "storm" | "partly";

export const DOT_PICTOGRAMS: Readonly<Record<WeatherKind, Glyph>> = {
  sun: G("#..#..#", ".#...#.", "..###..", "#.###.#", "..###..", ".#...#.", "#..#..#"),
  cloud: G(".......", "..##...", ".####..", "######.", "#######", ".#####.", "......."),
  partly: G("#.#....", ".#.##..", "#.####.", "..#####", ".######", "..####.", "......."),
  rain: G("..##...", ".####..", "######.", ".#####.", "#.#.#..", ".#.#.#.", "#.#.#.."),
  snow: G("#.....#", "..#.#..", ".#.#.#.", "#..#..#", ".#.#.#.", "..#.#..", "#.....#"),
  storm: G("..##...", ".####..", "######.", "...#...", "..##...", ".##....", "..#...."),
};

export function layoutPictogram(kind: WeatherKind): DotLayout {
  const g = DOT_PICTOGRAMS[kind];
  const dots: Dot[] = [];
  for (let y = 0; y < 7; y++) for (let x = 0; x < 7; x++) if (g[y][x] === "#") dots.push({ x, y });
  return { dots, cols: 7, rows: 7 };
}
