#!/usr/bin/env node
// Writes src/tester/buildInfo.ts for the Tester Hub's "What's new in this build".
//
//   node tools/changelog/gen.mjs            # normal: git history + docs/tester/LATEST.json
//   node tools/changelog/gen.mjs --check    # print what would be written, change nothing
//
// Works offline: it only reads the local git history (last 50 commits) and the bundled
// LATEST.json (or the example file). If git isn't available it writes a "dev" placeholder.
// Grouping by area happens at runtime in src/tester/model.ts so it stays unit-tested.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const out = join(root, "src/tester/buildInfo.ts");
const check = process.argv.includes("--check");

const git = (...args) => {
  try {
    return execFileSync("git", args, { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  } catch {
    return "";
  }
};

const version = JSON.parse(readFileSync(join(root, "package.json"), "utf8")).version ?? "0.0.0";
const sha = process.env.GITHUB_SHA || git("rev-parse", "HEAD") || "dev";
const branch = process.env.GITHUB_REF_NAME || git("rev-parse", "--abbrev-ref", "HEAD") || undefined;

// One record per commit: \x1e separates commits, \x1f separates fields; file list follows.
const raw = git("log", "-n", "50", "--no-color", "--name-only", "--format=%x1e%H%x1f%s%x1f%cI");
const commits = raw
  .split("\x1e")
  .map((block) => block.trim())
  .filter(Boolean)
  .map((block) => {
    const [head, ...files] = block.split("\n");
    const [hash, subject, date] = head.split("\x1f");
    const pr = /#(\d+)/.exec(subject ?? "")?.[1];
    return {
      sha: hash,
      subject: (subject ?? "").slice(0, 200),
      date,
      files: files.map((f) => f.trim()).filter(Boolean).slice(0, 12),
      ...(pr ? { pr: Number(pr) } : {}),
    };
  });

let latest = null;
let latestSource = "none";
for (const [file, source] of [
  [join(root, "docs/tester/LATEST.json"), "docs"],
  [join(root, "docs/tester/LATEST.example.json"), "example"],
]) {
  if (!existsSync(file)) continue;
  try {
    const text = readFileSync(file, "utf8");
    if (text.length > 50_000) throw new Error("LATEST.json is over 50 KB");
    latest = JSON.parse(text);
    latestSource = source;
    break;
  } catch (e) {
    console.warn(`[changelog] skipped ${file}: ${e.message}`);
  }
}

const info = {
  version,
  sha,
  builtAt: new Date().toISOString(),
  ...(branch && branch !== "HEAD" ? { branch } : {}),
  commits,
  latest,
  latestSource,
};

const text =
  "// Generated by tools/changelog/gen.mjs at build time. The committed copy is a dev placeholder.\n" +
  "// Do not edit by hand.\n" +
  `export const BUILD_INFO: unknown = ${JSON.stringify(info, null, 2)};\n`;
if (check) {
  console.log(text.slice(0, 2000));
} else {
  writeFileSync(out, text);
  console.log(`[changelog] wrote ${commits.length} commits, notes from ${latestSource} → src/tester/buildInfo.ts`);
}
