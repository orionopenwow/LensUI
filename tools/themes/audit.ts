// Writes docs/THEMES_AUDIT.md: how different every theme pack is from every other, which packs are
// near-duplicates, the featured twelve, and the family each remaining pack is filed under.
//   bun tools/themes/audit.ts          rewrite the document
//   bun tools/themes/audit.ts --check  exit 1 when the document is out of date
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { allPacks, contrastRatio, lighten, packById } from "../../src/themes/packs";
import { NEAR_DUPLICATE, distanceParts, nearest, packBase, packDistance, packScene } from "../../src/themes/distance";
import { FEATURED_LOOKS, FEEL_LABEL, FONT_LABEL, familyOf, featuredPacks, lookDistance, lookPack, lookScene, morePacks } from "../../src/themes/featured";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const out = join(root, "docs/THEMES_AUDIT.md");

export function buildAudit(): string {
  const packs = allPacks().filter((p) => p.tier !== "Custom");
  const lines: string[] = [];
  const push = (...l: string[]) => lines.push(...l);

  push(
    "# Theme audit",
    "",
    "Generated by `bun tools/themes/audit.ts` from `src/themes/distance.ts` and `src/themes/featured.ts`. Do not edit by hand; `src/__tests__/featuredThemes.test.ts` fails when it is out of date.",
    "",
    `${packs.length} packs were compared pair by pair. The distance adds up how far apart two packs are in surface colour and accent (OKLab), light or dark, corner radius and shape style, Dock style, window chrome (frame, buttons, icons) and animated backdrop. Under **${NEAR_DUPLICATE.toFixed(2)}** two packs read as the same theme with a tweak.`,
    "",
    "## The featured twelve",
    "",
    "Each is a whole look: palette, accent, glass, corners, Dock style and motion, window frame and buttons, icons, font, its own animated backdrop and a pointer family. No two share a backdrop.",
    "",
    "| Look | Character | Surface · accent | Corners | Glass | Dock | Frame · buttons | Icons | Font | Backdrop | Pointer | Feel |",
    "|---|---|---|---|---|---|---|---|---|---|---|---|",
  );
  for (const look of FEATURED_LOOKS) {
    const p = lookPack(look);
    push(
      `| **${p.label}** | ${look.character} | \`${packBase(p)}\` · \`${p.accent}\`${p.scheme === "light" ? " (light)" : ""} | ${p.radius}px${p.shapeStyle ? `, ${p.shapeStyle}` : ""} | ${Math.round(look.glass * 100)}%${look.blur ? `, ${look.blur}px blur` : ", solid"} | ${look.dock.style}, ${look.dock.magnification === "off" ? "no magnify" : look.dock.magnification + " magnify"}, ${look.dock.launch} launch | ${p.frameStyle} · ${p.controlStyle} | ${p.iconTheme}, ${p.iconShape} | ${FONT_LABEL[look.font]} | ${lookScene(look)} | ${look.cursor} | ${FEEL_LABEL[look.feel]} |`,
    );
  }

  let min = Infinity;
  let minPair = "";
  for (const a of FEATURED_LOOKS) for (const b of FEATURED_LOOKS) {
    if (a.id >= b.id) continue;
    const d = lookDistance(a, b);
    if (d < min) { min = d; minPair = `${lookPack(a).label} and ${lookPack(b).label}`; }
  }
  push("", `Closest two featured looks: ${minPair}, at ${min.toFixed(2)} (${(min / NEAR_DUPLICATE).toFixed(1)}× the near-duplicate line).`, "");

  push("### Contrast", "", "Text on the surface and on raised cards must reach 4.5:1; the accent must reach 3:1 against both.", "", "| Look | Text on surface | Text on cards | Accent on surface | Accent on cards |", "|---|---|---|---|---|");
  for (const look of FEATURED_LOOKS) {
    const p = packById(look.id)!;
    const base = packBase(p);
    const light = p.scheme === "light";
    const text = light ? "#18181B" : "#FAFAFA";
    const card = light ? "#FFFFFF" : lighten(base, 0.045);
    const r = (a: string, b: string) => `${contrastRatio(a, b).toFixed(1)}:1`;
    push(`| ${p.label} | ${r(text, base)} | ${r(text, card)} | ${r(p.accent, base)} | ${r(p.accent, card)} |`);
  }

  push("", "## Near-duplicates", "", `Pairs closer than ${NEAR_DUPLICATE.toFixed(2)}, closest first. None of these is deleted: the featured one of a pair leads, the other sits under More themes.`, "", "| Distance | Pack | Almost the same as | What still differs |", "|---|---|---|---|");
  const pairs: { d: number; a: string; b: string; why: string }[] = [];
  for (let i = 0; i < packs.length; i++) for (let j = i + 1; j < packs.length; j++) {
    const d = packDistance(packs[i], packs[j]);
    if (d >= NEAR_DUPLICATE) continue;
    const parts = distanceParts(packs[i], packs[j]);
    const why = (Object.entries(parts) as [string, number][]).filter(([, v]) => v > 0.02).sort((x, y) => y[1] - x[1]).map(([k]) => k).join(", ") || "nothing visible";
    pairs.push({ d, a: packs[i].label, b: packs[j].label, why });
  }
  pairs.sort((x, y) => x.d - y.d);
  for (const p of pairs) push(`| ${p.d.toFixed(2)} | ${p.a} | ${p.b} | ${p.why} |`);
  const inPair = new Set(pairs.flatMap((p) => [p.a, p.b]));
  push("", `${pairs.length} pairs, ${inPair.size} packs involved.`, "");

  push("## More themes, by family", "", `The other ${morePacks().filter((p) => p.tier !== "Custom").length} packs, filed under the featured look each is closest to. Community packs keep their credit and link in the gallery.`, "");
  const fams = new Map<string, { label: string; d: number; scene: string; near: string }[]>();
  for (const p of morePacks()) {
    if (p.tier === "Custom") continue;
    const fam = familyOf(p);
    const n = nearest(p, packs)!;
    (fams.get(fam.label) ?? fams.set(fam.label, []).get(fam.label)!).push({ label: p.label, d: packDistance(p, fam), scene: packScene(p), near: `${n.pack.label} (${n.distance.toFixed(2)})` });
  }
  for (const f of featuredPacks()) {
    const rows = fams.get(f.label);
    if (!rows?.length) continue;
    rows.sort((a, b) => a.d - b.d);
    push(`### Like ${f.label} (${rows.length})`, "", "| Pack | Distance from the featured look | Its closest pack overall |", "|---|---|---|");
    for (const r of rows) push(`| ${r.label} | ${r.d.toFixed(2)} | ${r.near} |`);
    push("");
  }
  return lines.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
}

if (import.meta.main) {
  const text = buildAudit();
  if (process.argv.includes("--check")) {
    const cur = existsSync(out) ? readFileSync(out, "utf8") : "";
    if (cur !== text) { console.error("docs/THEMES_AUDIT.md is out of date: run `bun tools/themes/audit.ts`"); process.exit(1); }
    console.log("[themes] audit is current");
  } else {
    writeFileSync(out, text);
    console.log(`[themes] wrote ${out}`);
  }
}
