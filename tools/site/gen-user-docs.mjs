// Writes docs/guide-for-users/*.md from the Lens Guide's own data, so the how-tos only mention
// settings, commands and shortcuts that exist:
//   lessons   guide/*.md            (or tools/site/vendor/guide/lessons/ until the Guide is merged)
//   settings  src/guide/index.json  (or tools/site/vendor/guide/index.json)
// Usage: node tools/site/gen-user-docs.mjs
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync, rmSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const vendor = join(root, "tools/site/vendor/guide");
const lessonDir = existsSync(join(root, "guide")) ? join(root, "guide") : join(vendor, "lessons");
const indexFile = existsSync(join(root, "src/guide/index.json")) ? join(root, "src/guide/index.json") : join(vendor, "index.json");
const out = join(root, "docs/guide-for-users");
const index = JSON.parse(readFileSync(indexFile, "utf8"));
const tabs = Object.fromEntries(index.tabs.map((t) => [t.id, t.label]));

function where(show) {
  if (!show) return "";
  const [surface, tab, label] = show.split(":");
  if (surface === "settings") return `Settings › ${tabs[tab] ?? tab}${label ? ` › ${label}` : ""}`;
  return { dock: "The dock", palette: "The palette (Alt+Space)", topbar: "The top bar", command: "Lens Command", wallpaper: "The desktop" }[surface] ?? "";
}

function lesson(md) {
  const fm = md.match(/^---\n([\s\S]*?)\n---\n/);
  const meta = Object.fromEntries((fm?.[1] ?? "").split("\n").map((l) => l.split(/:\s(.*)/s).slice(0, 2)).map(([k, v]) => [k, (v ?? "").trim().replace(/^"(.*)"$/, "$1")]));
  const body = md.slice(fm ? fm[0].length : 0);
  const steps = body.split(/^## /m).slice(1).map((s) => {
    const [title, ...rest] = s.split("\n");
    const directives = {};
    const text = [];
    for (const l of rest) {
      const d = l.match(/^(show|check|anchor|success|requires):\s*(.*)$/);
      if (d) directives[d[1]] = d[2];
      else text.push(l);
    }
    return { title: title.trim(), text: text.join("\n").trim(), where: where(directives.show), success: directives.success };
  });
  return { meta, steps };
}

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
const HEAD = (src) => `<!-- Generated by tools/site/gen-user-docs.mjs from ${src}. Edit the source, not this file. -->\n\n`;

const lessons = readdirSync(lessonDir).filter((f) => f.endsWith(".md")).sort();
const pages = [];
for (const f of lessons) {
  const { meta, steps } = lesson(readFileSync(join(lessonDir, f), "utf8"));
  const slug = f.replace(/^\d+-/, "").replace(/\.md$/, "");
  const md = `${HEAD(`guide/${f}`)}# ${meta.title}

${meta.summary ?? ""}${meta.minutes ? ` About ${meta.minutes} minutes.` : ""}
${meta.requires ? `\n> Needs: ${meta.requires}${meta.requiresNote ? ` — ${meta.requiresNote}` : ""}\n` : ""}
${steps.map((s, i) => `## ${i + 1}. ${s.title}\n\n${s.where ? `**Where:** ${s.where}\n\n` : ""}${s.text}${s.success ? `\n\n_You'll know it worked when:_ ${s.success}` : ""}`).join("\n\n")}

---

In Lens, open the Guide (the **?** in the top bar, or type \`/guide\` in Lens Command) to take this as an interactive lesson that notices each step.
`;
  writeFileSync(join(out, `${slug}.md`), md);
  pages.push({ slug, title: meta.title, summary: meta.summary ?? "" });
}

// Settings reference: every card and setting the Guide knows, grouped by Settings tab.
const byTab = {};
for (const e of index.entries.filter((e) => (e.kind === "card" || e.kind === "setting") && e.target?.tab)) (byTab[e.target.tab] ??= []).push(e);
let ref = `${HEAD("src/guide/index.json")}# Settings reference

Every card and option in Lens Settings, grouped by tab. Each line is where to find it: open Settings (the gear in the dock or top bar), pick the tab, then the card.

`;
for (const t of index.tabs) {
  const list = byTab[t.id];
  if (!list?.length) continue;
  ref += `## ${t.label}\n\n`;
  const cards = list.filter((e) => e.kind === "card");
  for (const c of cards) {
    const opts = list.filter((e) => e.kind === "setting" && e.target.card === c.target.card).map((e) => e.title);
    let t = (c.text ?? "").replace(/\s+/g, " ").trim();
    const again = t.indexOf(c.title, 1);
    if (again > 0) t = t.slice(0, again).trim();
    if (t.length > 200) t = t.slice(0, t.lastIndexOf(". ", 200) + 1 || 200);
    const blurb = t && t !== c.title ? ` — ${t}` : "";
    ref += `- **${c.title}**${blurb}${opts.length ? `\n  Options: ${[...new Set(opts)].join(", ")}.` : ""}\n`;
  }
  const loose = list.filter((e) => e.kind === "setting" && !cards.some((c) => c.target.card === e.target.card));
  if (loose.length) ref += `- Also here: ${[...new Set(loose.map((e) => e.title))].join(", ")}.\n`;
  ref += "\n";
}
writeFileSync(join(out, "settings-reference.md"), ref);

// Commands and shortcuts.
const cmds = index.entries.filter((e) => e.kind === "command");
const keys = index.entries.filter((e) => e.kind === "hotkey");
writeFileSync(
  join(out, "commands-and-shortcuts.md"),
  `${HEAD("src/guide/index.json")}# Commands and shortcuts

## Things you can type

Type these in Lens Command, the palette (Alt+Space) or the dock's Ask field. They work offline, with no AI model, and run straight away (risky ones ask first). Try them on the website's [command demo](https://orionopenwow.github.io/lensui/try.html#command).

| What | Try typing |
| :--- | :--- |
${cmds.map((c) => `| ${c.title} | ${(c.examples ?? []).map((x) => `\`${x}\``).join(", ")} |`).join("\n")}

## Keyboard shortcuts

| Keys | What it does |
| :--- | :--- |
${keys.map((k) => `| \`${k.title}\` | ${k.text.replace(k.title, "").trim()} |`).join("\n")}

Shortcuts that would take keys away from other apps are off until you turn them on in Settings.
`
);

writeFileSync(
  join(out, "README.md"),
  `${HEAD("guide/*.md and src/guide/index.json")}# Lens user guide

Short, practical how-tos. They are generated from the same data the in-app Guide uses, so every setting named here exists.

## Lessons

${pages.map((p) => `- [${p.title}](./${p.slug}.md) — ${p.summary}`).join("\n")}

## Reference

- [Settings reference](./settings-reference.md) — every card and option, by Settings tab.
- [Commands and shortcuts](./commands-and-shortcuts.md) — what you can type, and the keyboard map.

Something wrong or missing? [Open an issue](https://github.com/orionopenwow/LensUI/issues).
`
);
console.log(`user docs: ${pages.length} lessons + settings reference (${Object.values(byTab).flat().length} entries) + commands (${cmds.length}) + shortcuts (${keys.length}) from ${indexFile.replace(root + "/", "")}`);
