#!/usr/bin/env node
// Builds src/setup/whatsNew.ts from CHANGELOG.md: for every released version, its headline
// bullets per section, for the setup's "What's new" page (docs/SETUP.md). The file is committed;
// src/__tests__/setupFlow.test.ts fails when it is out of date.
//
//   node tools/setup/whats-new.mjs           # write
//   node tools/setup/whats-new.mjs --check   # exit 1 if stale
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const OUT = join(root, "src/setup/whatsNew.ts");

/** First sentence of a bullet, markdown removed, short enough for one line in the setup. */
function headline(text) {
  const plain = text
    .replace(/\*\*(.+?)\*\*/g, "$1")
    .replace(/`([^`]+)`/g, "$1")
    .replace(/\[([^\]]+)\]\([^)]+\)/g, "$1")
    .replace(/\\\\/g, "\\")
    .replace(/\s+/g, " ")
    .trim();
  const lead = plain.split(/(?<=[.;])\s/)[0].replace(/[.;:]$/, "");
  if (lead.length <= 120) return lead;
  // Cut at a word boundary so the line never ends mid-word.
  const cut = lead.slice(0, 118);
  return `${cut.slice(0, cut.lastIndexOf(" ")).replace(/[,;:]$/, "")}…`;
}

export function parseChangelog(md) {
  const releases = [];
  let rel = null;
  let section = null;
  let bullet = null;
  const flush = () => {
    if (bullet && section) section.items.push(headline(bullet));
    bullet = null;
  };
  for (const line of md.replace(/\r\n/g, "\n").split("\n")) {
    const v = /^## \[(\d+\.\d+\.\d+)\](?: - (\S+))?/.exec(line);
    if (/^## /.test(line)) {
      flush();
      rel = v ? { version: v[1], date: v[2] ?? "", sections: [] } : null;
      if (rel) releases.push(rel);
      section = null;
      continue;
    }
    if (!rel) continue;
    const h = /^### (.+)/.exec(line);
    if (h) {
      flush();
      section = { title: h[1].trim(), items: [] };
      // "Developer" entries (dev-only tools such as Mission Control) are not shown to people.
      if (section.title !== "Developer") rel.sections.push(section);
      continue;
    }
    if (/^- /.test(line)) {
      flush();
      bullet = line.slice(2);
    } else if (bullet && /^\s+\S/.test(line)) {
      bullet += ` ${line.trim()}`;
    } else if (!line.trim()) {
      flush();
    }
  }
  flush();
  return releases.map((r) => ({ ...r, sections: r.sections.filter((s) => s.items.length) }));
}

export function render(releases) {
  return `// GENERATED by tools/setup/whats-new.mjs from CHANGELOG.md — do not edit.
// Rebuild: node tools/setup/whats-new.mjs
export interface WhatsNewSection {
  title: string;
  items: string[];
}

export interface WhatsNewRelease {
  version: string;
  date: string;
  sections: WhatsNewSection[];
}

export const WHATS_NEW: WhatsNewRelease[] = ${JSON.stringify(releases, null, 2)};
`;
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const text = render(parseChangelog(readFileSync(join(root, "CHANGELOG.md"), "utf8")));
  if (process.argv.includes("--check")) {
    let old = "";
    try {
      old = readFileSync(OUT, "utf8");
    } catch {}
    if (old !== text) {
      console.error("src/setup/whatsNew.ts is stale: run node tools/setup/whats-new.mjs");
      process.exit(1);
    }
  } else {
    writeFileSync(OUT, text);
    console.log("wrote src/setup/whatsNew.ts");
  }
}
