// Writes src/guide/index.json from the repository (settings cards, docs, catalogues, lessons).
//   node tools/guide/build-index.mjs           write the index
//   node tools/guide/build-index.mjs --check   fail if the committed index is stale
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { buildIndex } from "./extract.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const out = join(root, "src/guide/index.json");
const outTs = join(root, "src/guide/indexData.ts");
const index = buildIndex(root);
const json = JSON.stringify(index, null, 1) + "\n";
// The app imports the index as a TS module (no resolveJsonModule needed); index.json is the same
// data for tools and tests.
const ts = `// GENERATED by tools/guide/build-index.mjs — do not edit. Rebuild: node tools/guide/build-index.mjs\nimport type { GuideIndex } from "./types";\n\nexport const GUIDE_INDEX: GuideIndex = ${JSON.stringify(index)} as GuideIndex;\n`;

if (process.argv.includes("--check")) {
  const current = existsSync(out) ? readFileSync(out, "utf8") : "";
  const currentTs = existsSync(outTs) ? readFileSync(outTs, "utf8") : "";
  if (current !== json || currentTs !== ts) {
    console.error("src/guide/index.json is out of date. Run: node tools/guide/build-index.mjs");
    process.exit(1);
  }
  console.log(`[guide] index up to date (${index.entries.length} entries, ${index.lessons.length} lessons)`);
} else {
  writeFileSync(out, json);
  writeFileSync(outTs, ts);
  const kinds = {};
  for (const e of index.entries) kinds[e.kind] = (kinds[e.kind] ?? 0) + 1;
  console.log(`[guide] wrote ${index.entries.length} entries, ${index.lessons.length} lessons`, kinds);
}
