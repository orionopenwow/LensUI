#!/usr/bin/env node
// Regenerates the auto-derived parts of docs/brain/*:
//   docs/brain/generated/commands.md   IPC command inventory (from lib.rs generate_handler!), grouped by module
//   docs/brain/generated/windows.md    Tauri windows (tauri.conf.json) + frontend routes (src/main.tsx)
//   docs/brain/generated/loc.md        lines/files per area (Rust, TS/TSX, CSS, docs)
//   docs/brain/generated/patterns.md   counts of bug-prone patterns (see PATTERNS below)
//   docs/brain/generated/prs.md        open PRs (only when `gh` is available and authenticated)
// Usage: node tools/brain/refresh.mjs [--check]
//   --check  exit 1 if any generated file would change (used by .github/workflows/brain.yml)
import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync, existsSync } from "node:fs";
import { join, relative, extname, sep } from "node:path";
import { execSync } from "node:child_process";

const ROOT = process.cwd();
const OUT = join(ROOT, "docs/brain/generated");
const CHECK = process.argv.includes("--check");
const SKIP = new Set(["node_modules", "target", "dist", ".git", "out", "shots", ".cache", "golden", "gen"]);

function walk(dir, acc = []) {
  if (!existsSync(dir)) return acc;
  for (const name of readdirSync(dir)) {
    if (SKIP.has(name)) continue;
    const p = join(dir, name);
    const s = statSync(p);
    if (s.isDirectory()) walk(p, acc);
    else acc.push(p);
  }
  return acc;
}
const read = (p) => readFileSync(p, "utf8");
const lines = (p) => read(p).split("\n").length;

// ---------- commands ----------
function commands() {
  const lib = read(join(ROOT, "src-tauri/src/lib.rs"));
  const m = lib.match(/generate_handler!\[([\s\S]*?)\]\)/);
  const body = m ? m[1] : "";
  const names = [...body.matchAll(/([A-Za-z_][\w:]*)\s*,/g)].map((x) => x[1]).filter((n) => !n.startsWith("//"));
  const groups = {};
  for (const n of names) {
    const parts = n.split("::");
    const g = parts.length > 1 ? parts[parts.length - 2] : "lib";
    (groups[g] ||= []).push(parts[parts.length - 1]);
  }
  const keys = Object.keys(groups).sort();
  let s = `# IPC command inventory\n\nGenerated by \`tools/brain/refresh.mjs\` from \`src-tauri/src/lib.rs\`. **${names.length} commands** in ${keys.length} modules.\n\n| Module | Count | Commands |\n|---|---|---|\n`;
  for (const k of keys) s += `| \`${k}\` | ${groups[k].length} | ${groups[k].map((c) => "`" + c + "`").join(", ")} |\n`;
  return s;
}

// ---------- windows ----------
function windows() {
  const conf = JSON.parse(read(join(ROOT, "src-tauri/tauri.conf.json")));
  const main = read(join(ROOT, "src/main.tsx"));
  const routes = [...main.matchAll(/^\s{2}(\w+):\s*lazy\(\(\)\s*=>\s*(?:\n\s*)?import\("([^"]+)"\)/gm)].map((m) => [m[1], m[2]]);
  let s = `# Windows and routes\n\nGenerated from \`src-tauri/tauri.conf.json\` and \`src/main.tsx\`.\n\n## Declared windows (${conf.app.windows.length})\n\n| Label | Visible at start | Size |\n|---|---|---|\n`;
  for (const w of conf.app.windows) s += `| \`${w.label}\` | ${w.visible === false ? "no (on demand)" : "yes"} | ${w.width}×${w.height} |\n`;
  const declared = new Set(conf.app.windows.map((w) => w.label));
  s += `\n## Frontend routes (${routes.length}) — \`index.html?surface=<id>\`\n\n| Route | Module | Window |\n|---|---|---|\n`;
  for (const [id, mod] of routes) s += `| \`${id}\` | \`${mod}\` | ${declared.has(id) ? "declared" : "built at runtime"} |\n`;
  return s;
}

// ---------- LOC ----------
function loc() {
  const files = walk(join(ROOT, "src")).concat(walk(join(ROOT, "src-tauri/src")), walk(join(ROOT, "extensions")), walk(join(ROOT, "tools")), walk(join(ROOT, "docs")));
  const areas = {};
  const big = [];
  for (const f of files) {
    const ext = extname(f);
    if (![".rs", ".ts", ".tsx", ".css", ".js", ".mjs", ".md"].includes(ext)) continue;
    const rel = relative(ROOT, f).split(sep).join("/");
    if (rel.startsWith("docs/brain/generated/")) continue; // its own output would never settle
    const parts = rel.split("/");
    let area;
    if (rel.startsWith("src-tauri/src/")) area = "rust:" + (parts.length > 3 ? parts[2] : parts[2].replace(/\.rs$/, "").replace(/^win_.*/, "win_*"));
    else if (rel.startsWith("src/")) area = "web:" + (parts.length > 2 ? parts[1] : "(root)");
    else area = parts[0] + (parts[1] && parts[0] !== "docs" ? "/" + parts[1] : "");
    const n = lines(f);
    const a = (areas[area] ||= { files: 0, lines: 0 });
    a.files++;
    a.lines += n;
    if ([".rs", ".ts", ".tsx"].includes(ext) && !rel.includes("generated") && !rel.includes("indexData")) big.push([rel, n]);
  }
  const rows = Object.entries(areas).sort((a, b) => b[1].lines - a[1].lines);
  const tot = rows.reduce((t, [, v]) => ({ files: t.files + v.files, lines: t.lines + v.lines }), { files: 0, lines: 0 });
  let s = `# Size by area\n\nGenerated by \`tools/brain/refresh.mjs\` (line counts include blanks and comments). Total: **${tot.files} files, ${tot.lines.toLocaleString("en-US")} lines**.\n\n| Area | Files | Lines |\n|---|---|---|\n`;
  for (const [k, v] of rows) s += `| \`${k}\` | ${v.files} | ${v.lines.toLocaleString("en-US")} |\n`;
  big.sort((a, b) => b[1] - a[1]);
  s += `\n## Largest source files\n\n| File | Lines |\n|---|---|\n`;
  for (const [f, n] of big.slice(0, 25)) s += `| \`${f}\` | ${n.toLocaleString("en-US")} |\n`;
  return s;
}

// ---------- bug-prone patterns ----------
const PATTERNS = [
  ["Rust `.unwrap()` outside tests", "rs", /\.unwrap\(\)/g, (rel) => !rel.includes("/tests/") && !rel.endsWith("tests.rs")],
  ["Rust `.expect(` outside tests", "rs", /\.expect\(/g, (rel) => !rel.includes("/tests/") && !rel.endsWith("tests.rs")],
  ["Rust `unsafe` blocks", "rs", /\bunsafe\s*\{/g, () => true],
  ["`setInterval(` (check each has a clear)", "ts", /setInterval\(/g, (rel) => !rel.includes("__tests__")],
  ["`addEventListener(` (check each has a remove)", "ts", /addEventListener\(/g, (rel) => !rel.includes("__tests__")],
  ["`listen(` from @tauri-apps/api/event (check unlisten)", "ts", /\blisten(?:<[^>]*>)?\(/g, (rel) => !rel.includes("__tests__")],
  // Only intrinsic (lower-case) elements: `<Section title=…>` is a prop, `<button title=…>` is a browser tooltip.
  ["native `title=` tooltips on HTML elements (banned by AGENTS.md)", "tsx", /<(?!iframe\b)[a-z][\w-]*\b[^<]*?\stitle=\{?["'`]/g, (rel) => !rel.includes("__tests__")],
  ["hard-coded hex colours in TSX", "tsx", /["'`]#[0-9a-fA-F]{6}["'`]/g, (rel) => !rel.includes("__tests__")],
  ["`.catch(() => {})` (silently swallowed errors)", "ts", /\.catch\(\(\)\s*=>\s*\{\s*\}\)/g, (rel) => !rel.includes("__tests__")],
];
function patterns() {
  const files = walk(join(ROOT, "src")).concat(walk(join(ROOT, "src-tauri/src")));
  let s = `# Bug-prone pattern counts\n\nGenerated by \`tools/brain/refresh.mjs\`. These are signals, not bugs: each hit needs a human look. Track the trend; it should go down.\n\n| Pattern | Hits | Top files |\n|---|---|---|\n`;
  for (const [label, kind, re, keep] of PATTERNS) {
    const per = {};
    let total = 0;
    for (const f of files) {
      const rel = relative(ROOT, f).split(sep).join("/");
      const ext = extname(f);
      const ok = kind === "rs" ? ext === ".rs" : kind === "tsx" ? ext === ".tsx" : ext === ".ts" || ext === ".tsx";
      if (!ok || !keep(rel)) continue;
      let text = read(f);
      // Inline `#[cfg(test)] mod tests` blocks sit at the end of Rust files by convention; don't count them.
      if (ext === ".rs") text = text.split(/#\[cfg\(test\)\]/)[0];
      const n = (text.match(re) || []).length;
      if (n) {
        per[rel] = n;
        total += n;
      }
    }
    const top = Object.entries(per).sort((a, b) => b[1] - a[1]).slice(0, 4).map(([f, n]) => `\`${f}\` (${n})`).join(", ");
    s += `| ${label} | ${total} | ${top || "—"} |\n`;
  }
  return s;
}

// ---------- open PRs ----------
function prs() {
  try {
    const raw = execSync('gh api "repos/orionopenwow/LensUI/pulls?state=open&per_page=100"', { stdio: ["ignore", "pipe", "ignore"] }).toString();
    const list = JSON.parse(raw);
    let s = `# Open pull requests\n\nGenerated by \`tools/brain/refresh.mjs\` via \`gh\`. Features listed here are "in PR" in FEATURES.md.\n\n| # | Branch | Title |\n|---|---|---|\n`;
    // The brain's own refresh PR would otherwise list itself and drift every week.
    for (const p of list.filter((x) => !x.head.ref.startsWith("brain/"))) s += `| #${p.number} | \`${p.head.ref}\` | ${p.title.replace(/\|/g, "\\|")} |\n`;
    return s;
  } catch {
    return null;
  }
}

mkdirSync(OUT, { recursive: true });
const outputs = { "commands.md": commands(), "windows.md": windows(), "loc.md": loc(), "patterns.md": patterns() };
const p = prs();
if (p) outputs["prs.md"] = p;
let drift = false;
for (const [name, text] of Object.entries(outputs)) {
  const file = join(OUT, name);
  const old = existsSync(file) ? read(file) : "";
  if (old !== text) {
    drift = true;
    if (!CHECK) writeFileSync(file, text);
  }
  console.log(`${old === text ? "same   " : CHECK ? "DRIFT  " : "wrote  "} docs/brain/generated/${name}`);
}
if (CHECK && drift) process.exit(1);
