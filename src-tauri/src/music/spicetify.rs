//! Generates an optional "Lens" theme for Spicetify (pure, std-only, apart from `detect`).
//!
//! Lens never patches Spotify and never runs Spicetify. It writes `color.ini` + `user.css`
//! that the user can apply themselves with Spicetify; see docs/MUSIC.md for the caveats
//! (Spotify updates undo it, and modifying the client may conflict with Spotify's terms).

use super::color::{contrast, ensure_contrast, mix, parse_hex, to_hex, Rgb};

/// The Lens tokens the theme is generated from.
#[derive(Debug, Clone, PartialEq)]
pub struct LensTokens {
    /// Surface base (`--lens-pack-base`), e.g. `#09090B`.
    pub base: String,
    /// Accent (`--lens-accent`).
    pub accent: String,
    /// Light packs flip the ink.
    pub light: bool,
    /// Corner radius in px (0–20).
    pub radius: u32,
}

impl Default for LensTokens {
    fn default() -> Self {
        LensTokens { base: "#09090B".into(), accent: "#FAFAFA".into(), light: false, radius: 8 }
    }
}

/// Keys Spicetify reads from a `color.ini` scheme (from the community themes' schemes).
pub const COLOR_KEYS: [&str; 20] = [
    "text",
    "subtext",
    "nav-active-text",
    "main",
    "sidebar",
    "player",
    "card",
    "shadow",
    "main-secondary",
    "button",
    "button-secondary",
    "button-active",
    "button-disabled",
    "nav-active",
    "play-button",
    "tab-active",
    "notification",
    "notification-error",
    "playback-bar",
    "misc",
];

/// Colour for each key, as `rrggbb`.
pub fn scheme(t: &LensTokens) -> Vec<(&'static str, String)> {
    let base = parse_hex(&t.base).unwrap_or(Rgb::new(9, 9, 11));
    let ink = if t.light { Rgb::new(9, 9, 11) } else { Rgb::new(250, 250, 250) };
    let accent_raw = parse_hex(&t.accent).unwrap_or(ink);
    let main = base;
    let sidebar = mix(base, if t.light { Rgb::new(255, 255, 255) } else { Rgb::new(0, 0, 0) }, 0.35);
    let card = mix(base, ink, 0.06);
    let player = mix(base, ink, 0.04);
    let accent = ensure_contrast(accent_raw, main, 3.0);
    let text = ensure_contrast(ink, main, 7.0);
    let subtext = ensure_contrast(mix(ink, base, 0.42), main, 4.5);
    // The play button carries its own ink: pick whichever of black/white reads on the accent.
    let on_accent = if contrast(Rgb::new(0, 0, 0), accent) > contrast(Rgb::new(255, 255, 255), accent) { Rgb::new(0, 0, 0) } else { Rgb::new(255, 255, 255) };
    let v = |c: Rgb| to_hex(c);
    vec![
        ("text", v(text)),
        ("subtext", v(subtext)),
        ("nav-active-text", v(on_accent)),
        ("main", v(main)),
        ("sidebar", v(sidebar)),
        ("player", v(player)),
        ("card", v(card)),
        ("shadow", v(Rgb::new(0, 0, 0))),
        ("main-secondary", v(mix(base, ink, 0.10))),
        ("button", v(accent)),
        ("button-secondary", v(subtext)),
        ("button-active", v(mix(accent, ink, 0.18))),
        ("button-disabled", v(mix(ink, base, 0.70))),
        ("nav-active", v(accent)),
        ("play-button", v(accent)),
        ("tab-active", v(mix(base, ink, 0.12))),
        ("notification", v(mix(base, accent, 0.35))),
        ("notification-error", v(ensure_contrast(Rgb::new(229, 72, 77), main, 3.0))),
        ("playback-bar", v(accent)),
        ("misc", v(mix(ink, base, 0.55))),
    ]
}

pub fn color_ini(t: &LensTokens) -> String {
    let mut s = String::from("; Lens theme for Spicetify, generated by Lens UI from your current Lens theme.\n; Re-export from Lens after changing your Lens theme. Apply it yourself with Spicetify.\n\n[Lens]\n");
    for (k, v) in scheme(t) {
        s.push_str(&format!("{:<20}= {}\n", k, v));
    }
    s
}

/// The stylesheet: slim rail + library, artwork-tinted headers, frosted now-playing,
/// dense calm type, monospace metadata. Spotify's class names change between versions, so
/// every rule is a cosmetic best effort; nothing hides controls.
