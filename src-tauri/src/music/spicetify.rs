/// Checks that CSS braces/comments balance and every `--spice-*` variable used is one
/// Spicetify defines from `color.ini` (`--spice-<key>` or `--spice-rgb-<key>`).
pub fn validate_css(css: &str) -> Result<(), String> {
    let mut depth: i32 = 0;
    let mut chars = css.chars().peekable();
    let mut in_comment = false;
    let mut in_str: Option<char> = None;
    while let Some(c) = chars.next() {
        if in_comment {
            if c == '*' && chars.peek() == Some(&'/') {
                chars.next();
                in_comment = false;
            }
            continue;
        }
        if let Some(q) = in_str {
            if c == q {
                in_str = None;
            }
            continue;
        }
        match c {
            '/' if chars.peek() == Some(&'*') => {
                chars.next();
                in_comment = true;
            }
            '"' | '\'' => in_str = Some(c),
            '{' => depth += 1,
            '}' => {
                depth -= 1;
                if depth < 0 {
                    return Err("unbalanced '}'".into());
                }
            }
            _ => {}
        }
    }
    if in_comment || in_str.is_some() || depth != 0 {
        return Err("unterminated comment, string or block".into());
    }
    let mut rest = css;
    while let Some(i) = rest.find("--spice-") {
        let tail = &rest[i + 8..];
        let name: String = tail.chars().take_while(|c| c.is_ascii_alphanumeric() || *c == '-').collect();
        let key = name.strip_prefix("rgb-").unwrap_or(&name);
        if !COLOR_KEYS.contains(&key) {
            return Err(format!("unknown Spicetify variable --spice-{}", name));
        }
        rest = &tail[name.len()..];
    }
    Ok(())
}

/// The commands the user runs themselves.
pub fn instructions(installed: bool) -> Vec<String> {
    let mut v = Vec::new();
    if !installed {
        v.push("Spicetify isn't installed. Lens doesn't install it; see https://spicetify.app if you want to use it.".into());
    }
    v.push("spicetify config current_theme Lens color_scheme Lens".into());
    v.push("spicetify apply".into());
    v.push("To undo: spicetify restore".into());
    v
}

/// Where Spicetify keeps user themes (`%APPDATA%\spicetify\Themes`), and whether it looks
/// installed (that folder or `spicetify` on PATH). Detection only tailors the instructions.
pub fn detect() -> (bool, Option<std::path::PathBuf>) {
    let themes = std::env::var_os("APPDATA").map(|a| std::path::PathBuf::from(a).join("spicetify").join("Themes"));
    let folder = std::env::var_os("APPDATA").map(|a| std::path::PathBuf::from(a).join("spicetify")).is_some_and(|p| p.is_dir());
    let on_path = std::env::var_os("PATH").is_some_and(|p| {
        std::env::split_paths(&p).any(|d| d.join("spicetify.exe").is_file() || d.join("spicetify").is_file())
    });
    (folder || on_path, themes)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::music::color::contrast;

    fn hex_to(s: &str) -> Rgb {
        parse_hex(s).unwrap()
    }

    #[test]
    fn scheme_has_every_key_with_valid_hex() {
        let s = scheme(&LensTokens::default());
        assert_eq!(s.len(), COLOR_KEYS.len());
        for (k, v) in &s {
            assert!(COLOR_KEYS.contains(k));
            assert_eq!(v.len(), 6);
            assert!(parse_hex(v).is_some(), "{}={}", k, v);
        }
    }

    #[test]
    fn text_and_accent_readable_on_every_pack() {
        let packs = [
            ("#09090B", "#FAFAFA", false),
            ("#1E1E2E", "#CBA6F7", false),
            ("#2E3440", "#88C0D0", false),
            ("#0D0B09", "#FCEE0A", false),
            ("#EEEEF0", "#2563EB", true),
            ("#F5F1E8", "#C2410C", true),
            ("#002B36", "#2AA198", false),
            ("#F5F1E8", "#FFF7E0", true), // pale accent on a light pack gets darkened
        ];
        for (base, accent, light) in packs {
            let s: std::collections::HashMap<_, _> = scheme(&LensTokens { base: base.into(), accent: accent.into(), light, radius: 8 }).into_iter().collect();
            let main = hex_to(&s["main"]);
            assert!(contrast(hex_to(&s["text"]), main) >= 7.0, "text on {}", base);
            assert!(contrast(hex_to(&s["subtext"]), main) >= 4.5, "subtext on {}", base);
            assert!(contrast(hex_to(&s["button"]), main) >= 3.0, "accent on {}", base);
            assert!(contrast(hex_to(&s["nav-active-text"]), hex_to(&s["play-button"])) >= 3.0);
        }
    }

    #[test]
    fn ini_and_css_are_valid() {
        let t = LensTokens { radius: 30, ..Default::default() };
        let ini = color_ini(&t);
        assert!(ini.contains("[Lens]"));
        assert_eq!(ini.lines().filter(|l| l.contains('=')).count(), COLOR_KEYS.len());
        let css = user_css(&t);
        validate_css(&css).unwrap();
        assert!(css.contains("--lens-radius: 20px"), "radius clamped");
        assert!(validate_css("a { b: c; ").is_err());
        assert!(validate_css("a { color: var(--spice-nope); }").is_err());
        assert!(validate_css("/* } */ a { content: \"}\"; color: var(--spice-rgb-text); }").is_ok());
    }

    #[test]
    fn instructions_never_run_anything() {
        let i = instructions(false);
        assert!(i[0].contains("doesn't install"));
        assert!(i.iter().any(|l| l == "spicetify apply"));
        assert!(i.iter().any(|l| l.contains("restore")));
    }
}
